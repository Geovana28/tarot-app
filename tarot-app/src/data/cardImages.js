export function getCardImage(imageKey) {
  if (!imageKey) return cardImages["card-back"];
  const cleanKey = imageKey.replace(/^Cartas\//, "").replace(/\.jpg$/, "");
  return cardImages[cleanKey] || cardImages["card-back"];
}
